<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Foundation\Auth\User as Authenticatable;
use Illuminate\Notifications\Notifiable;

class User extends Authenticatable
{
    use HasFactory, Notifiable;

    protected $fillable = [
        'name',
        'email',
        'phone',
        'role',
        'fcm_token',
        'avatar',
        'is_active',
        'password',
    ];

    protected $hidden = [
        'password',
        'remember_token',
    ];

    protected function casts(): array
    {
        return [
            'email_verified_at' => 'datetime',
            'password' => 'hashed',
            'is_active' => 'boolean',
        ];
    }

    public function tokens()
    {
        return $this->hasMany(PersonalAccessToken::class);
    }

    public function createToken(string $name = 'auth_token', array $abilities = ['*'])
    {
        $result = PersonalAccessToken::createTokenForUser($this, $name, $abilities);
        return (object)[
            'plainTextToken' => $result['plain_text_token'],
            'accessToken' => $result['token_instance'],
        ];
    }

    public function addresses()
    {
        return $this->hasMany(Address::class);
    }

    public function orders()
    {
        return $this->hasMany(Order::class, 'customer_id');
    }

    public function courierDeliveries()
    {
        return $this->hasMany(Order::class, 'courier_id');
    }

    public function isAdmin(): bool
    {
        return $this->role === 'admin';
    }

    public function isCourier(): bool
    {
        return $this->role === 'courier';
    }

    public function isCustomer(): bool
    {
        return $this->role === 'customer';
    }
}
